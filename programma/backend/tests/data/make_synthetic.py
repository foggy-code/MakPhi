"""Genera le strutture sintetiche di test a partire da 1UBQ (riproducibile, niente download).

    python tests/data/make_synthetic.py        (dalla cartella backend)

- ubq_dimer.pdb   omodimero C2: catena A = 1UBQ, catena B = copia ruotata di 180° attorno a un asse parallelo
                  a z e traslata finché la distanza minima tra atomi pesanti è ~3,8 Å (interfaccia di contatto,
                  nessuno scontro). Serve ai test su catene multiple, assemblaggi e interfacce.
- ubq_zn.pdb      1UBQ con uno ione Zn2+ (HETATM ZN, catena A, residuo 101) a 2,1 Å da NE2 di His68,
                  sull'asse centroide dell'anello → NE2, più due molecole d'acqua. Serve ai test su ligandi,
                  eteroatomi e geometria di coordinazione dei metalli.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np

HERE = Path(__file__).parent


def _atoms(lines: list[str]) -> list[str]:
    return [ln for ln in lines if ln.startswith("ATOM")]


def _xyz(line: str) -> np.ndarray:
    return np.array([float(line[30:38]), float(line[38:46]), float(line[46:54])])


def _with_xyz(line: str, xyz: np.ndarray, chain: str | None = None, serial: int | None = None) -> str:
    out = line
    if serial is not None:
        out = f"{out[:6]}{serial:5d}{out[11:]}"
    if chain is not None:
        out = f"{out[:21]}{chain}{out[22:]}"
    return f"{out[:30]}{xyz[0]:8.3f}{xyz[1]:8.3f}{xyz[2]:8.3f}{out[54:]}"


def make_dimer(atoms: list[str]) -> str:
    coords = np.array([_xyz(a) for a in atoms])
    heavy = np.array([a[76:78].strip() != "H" for a in atoms])
    centre = coords.mean(axis=0)
    rot = np.diag([-1.0, -1.0, 1.0])  # C2 attorno a z
    b0 = (coords - centre) @ rot.T + centre
    # traslazione perpendicolare all'asse (la simmetria C2 resta): per ogni direzione del piano xy il più
    # piccolo spostamento senza scontri (atomi pesanti ≥ 3,3 Å); si tiene quella con più contatti < 4,5 Å
    best = (-1, None)
    for angle in np.radians(np.arange(0.0, 360.0, 10.0)):
        unit = np.array([np.cos(angle), np.sin(angle), 0.0])
        for d in np.arange(10.0, 60.0, 0.1):
            moved = b0[heavy] + d * unit
            dist = np.sqrt(((coords[heavy][:, None, :] - moved[None, :, :]) ** 2).sum(-1))
            if dist.min() >= 3.3:
                contacts = int((dist < 4.5).sum())
                if contacts > best[0]:
                    best = (contacts, d * unit)
                break
    b = b0 + best[1]
    lines = ["HEADER    SYNTHETIC C2 HOMODIMER OF 1UBQ (BIOLOOM TESTS)",
             "REMARK   1 GENERATED BY tests/data/make_synthetic.py FROM 1UBQ"]
    serial = 1
    for chain, xyzs in (("A", coords), ("B", b)):
        for a, xyz in zip(atoms, xyzs):
            lines.append(_with_xyz(a, xyz, chain=chain, serial=serial))
            serial += 1
        last = atoms[-1]
        lines.append(f"TER   {serial:5d}      {last[17:20]} {chain}{last[22:26]}")
        serial += 1
    lines.append("END")
    return "\n".join(lines) + "\n"


def make_zn(atoms: list[str]) -> str:
    his = {a[12:16].strip(): _xyz(a) for a in atoms if a[17:20] == "HIS" and int(a[22:26]) == 68}
    ring = np.array([his[n] for n in ("CG", "ND1", "CD2", "CE1", "NE2")])
    direction = his["NE2"] - ring.mean(axis=0)
    zn = his["NE2"] + 2.1 * direction / np.linalg.norm(direction)
    serial = len(atoms) + 1
    lines = ["HEADER    1UBQ WITH A SYNTHETIC ZN2+ SITE (BIOLOOM TESTS)",
             "REMARK   1 GENERATED BY tests/data/make_synthetic.py FROM 1UBQ",
             *atoms]
    last = atoms[-1]
    lines.append(f"TER   {serial:5d}      {last[17:20]} A{last[22:26]}")
    # nome atomo nelle colonne 13-16: gli elementi di due lettere partono dalla colonna 13
    hets = [("ZN  ", " ZN", 101, zn, "ZN"),
            (" O  ", "HOH", 201, zn + np.array([0.0, 0.0, 2.1]), "O"),
            (" O  ", "HOH", 202, zn + np.array([0.0, 2.1, 0.0]), "O")]
    for i, (name, resn, resi, xyz, elem) in enumerate(hets, start=serial + 1):
        lines.append(f"HETATM{i:5d} {name} {resn:>3} A{resi:4d}    "
                     f"{xyz[0]:8.3f}{xyz[1]:8.3f}{xyz[2]:8.3f}  1.00 20.00          {elem:>2}")
    lines.append("END")
    return "\n".join(lines) + "\n"


def main() -> None:
    atoms = _atoms((HERE / "1UBQ.pdb").read_text(encoding="utf-8").splitlines())
    (HERE / "ubq_dimer.pdb").write_text(make_dimer(atoms), encoding="utf-8", newline="\n")
    (HERE / "ubq_zn.pdb").write_text(make_zn(atoms), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
